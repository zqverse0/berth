/// Client-to-server version and capability negotiation request.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct HandshakeRequest {
    /// Lowest detached RPC wire version accepted by the caller.
    pub minimum_wire_version: u32,
    /// Highest detached RPC wire version accepted by the caller.
    pub maximum_wire_version: u32,
    /// Capability ids the caller requires before issuing follow-up requests.
    pub required_capabilities: Vec<String>,
}

impl HandshakeRequest {
    /// Builds a current-version handshake with no mandatory capabilities.
    #[must_use]
    pub fn current() -> Self {
        Self::requiring(std::iter::empty::<&str>())
    }

    /// Builds a current-version handshake with explicit mandatory capabilities.
    #[must_use]
    pub fn requiring<I, S>(required_capabilities: I) -> Self
    where
        I: IntoIterator<Item = S>,
        S: AsRef<str>,
    {
        Self {
            minimum_wire_version: BERTH_TERM_WIRE_VERSION,
            maximum_wire_version: BERTH_TERM_WIRE_VERSION,
            required_capabilities: required_capabilities
                .into_iter()
                .map(|capability| capability.as_ref().to_owned())
                .collect(),
        }
    }

    /// Validates this request against the supplied capability list.
    pub fn validate_against(&self, supported_capabilities: &[&str]) -> Result<(), TerminalError> {
        if self.minimum_wire_version > BERTH_TERM_WIRE_VERSION
            || self.maximum_wire_version < BERTH_TERM_WIRE_VERSION
        {
            return Err(TerminalError::UnsupportedWireVersion {
                got: BERTH_TERM_WIRE_VERSION,
                minimum: self.minimum_wire_version,
                maximum: self.maximum_wire_version,
            });
        }

        if let Some(feature) = self
            .required_capabilities
            .iter()
            .find(|feature| !supported_capabilities.contains(&feature.as_str()))
        {
            return Err(TerminalError::UnsupportedCapability {
                feature: feature.clone(),
                supported: supported_capabilities
                    .iter()
                    .copied()
                    .map(str::to_owned)
                    .collect(),
            });
        }

        Ok(())
    }
}

/// Server-to-client version and capability negotiation response.
#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
pub struct HandshakeResponse {
    /// Detached RPC wire version selected for this connection.
    pub wire_version: u32,
    /// Capability ids supported by the daemon.
    pub capabilities: Vec<String>,
}

impl HandshakeResponse {
    /// Builds the response advertised by this protocol build.
    #[must_use]
    pub fn current() -> Self {
        Self {
            wire_version: BERTH_TERM_WIRE_VERSION,
            capabilities: SUPPORTED_CAPABILITIES
                .iter()
                .copied()
                .map(str::to_owned)
                .collect(),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::{
        daemon_instance_capability, daemon_instance_from_capabilities,
        daemon_instance_from_capability, HandshakeResponse, CAPABILITY_ATTACH_RENDER,
        CAPABILITY_ATTACH_WINDOWS_CONSOLE_KEY, CAPABILITY_CLI_CAPTURE_TARGET_ACTION,
        CAPABILITY_CLI_TARGET_ACTIONS, CAPABILITY_DAEMON_INSTANCE_PREFIX,
        DAEMON_INSTANCE_TOKEN_HEX_LEN, SUPPORTED_CAPABILITIES,
    };

    #[test]
    fn daemon_instance_capabilities_round_trip_through_a_handshake_list() {
        let token = "0123456789abcdef0123456789abcdef";
        assert_eq!(token.len(), DAEMON_INSTANCE_TOKEN_HEX_LEN);
        let entry = daemon_instance_capability(token);
        assert_eq!(entry, format!("{CAPABILITY_DAEMON_INSTANCE_PREFIX}{token}"));
        assert_eq!(daemon_instance_from_capability(&entry), Some(token));

        let mut capabilities: Vec<String> = SUPPORTED_CAPABILITIES
            .iter()
            .map(|value| (*value).to_owned())
            .collect();
        capabilities.push(entry);
        assert_eq!(
            daemon_instance_from_capabilities(&capabilities),
            Some(token)
        );
    }

    #[test]
    fn daemon_instance_capabilities_fail_closed_on_missing_or_malformed_entries() {
        // 旧 daemon 不广播该条目：必须得到「无法确认」，不得 panic 或猜测。
        assert_eq!(
            daemon_instance_from_capabilities(SUPPORTED_CAPABILITIES),
            None
        );
        let empty: [&str; 0] = [];
        assert_eq!(daemon_instance_from_capabilities(&empty), None);
        for malformed in [
            CAPABILITY_DAEMON_INSTANCE_PREFIX,
            "daemon.instance=not-hex",
            "daemon.instance=ab cd",
            "daemon.instance",
            "daemon.instances=deadbeef",
        ] {
            assert_eq!(
                daemon_instance_from_capability(malformed),
                None,
                "{malformed} must be rejected"
            );
        }
    }

    #[test]
    fn daemon_instance_capabilities_are_absent_from_the_baseline_list() {
        // token 是运行时值，基线能力列表不得固化任何实例身份。
        assert!(SUPPORTED_CAPABILITIES
            .iter()
            .all(|capability| !capability.starts_with(CAPABILITY_DAEMON_INSTANCE_PREFIX)));
    }

    #[test]
    fn current_handshake_advertises_attach_stream_capabilities() {
        let response = HandshakeResponse::current();

        assert!(response
            .capabilities
            .iter()
            .any(|capability| capability == CAPABILITY_ATTACH_RENDER));
        assert!(response
            .capabilities
            .iter()
            .any(|capability| capability == CAPABILITY_ATTACH_WINDOWS_CONSOLE_KEY));
    }

    #[test]
    fn current_handshake_advertises_cli_target_action_capabilities() {
        let response = HandshakeResponse::current();

        for expected in [
            CAPABILITY_CLI_TARGET_ACTIONS,
            CAPABILITY_CLI_CAPTURE_TARGET_ACTION,
        ] {
            assert!(
                response
                    .capabilities
                    .iter()
                    .any(|capability| capability == expected),
                "missing capability {expected}"
            );
        }
    }
}
