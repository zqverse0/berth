/// Reserved capability prefix for the daemon instance identity.
///
/// Entries are shaped `daemon.instance=<hex token>`. The token is generated by
/// the daemon at startup (it is a runtime value, so it is deliberately absent
/// from [`SUPPORTED_CAPABILITIES`]) and lets clients detect a restarted daemon
/// even when every other observable — endpoint path, session name, pane id and
/// pane generation — is unchanged.
pub const CAPABILITY_DAEMON_INSTANCE_PREFIX: &str = "daemon.instance=";

/// Hex length of the daemon instance token emitted by daemons (128 bits).
pub const DAEMON_INSTANCE_TOKEN_HEX_LEN: usize = 32;

/// Builds the capability entry that advertises `token` as the daemon instance.
#[must_use]
pub fn daemon_instance_capability(token: &str) -> String {
    format!("{CAPABILITY_DAEMON_INSTANCE_PREFIX}{token}")
}

/// Parses one capability entry into its daemon instance token.
///
/// Malformed entries (empty payload, non-hex payload) return `None` so callers
/// fail closed instead of comparing a garbage token.
#[must_use]
pub fn daemon_instance_from_capability(capability: &str) -> Option<&str> {
    let token = capability.strip_prefix(CAPABILITY_DAEMON_INSTANCE_PREFIX)?;
    if token.is_empty() || !token.bytes().all(|byte| byte.is_ascii_hexdigit()) {
        return None;
    }
    Some(token)
}

/// Parses a handshake capability list into the advertised daemon instance token.
///
/// `None` means the connected daemon does not advertise a daemon instance
/// identity (older daemon, or malformed entry); callers must treat captured
/// bindings as unverifiable rather than guessed.
#[must_use]
pub fn daemon_instance_from_capabilities<S>(capabilities: &[S]) -> Option<&str>
where
    S: AsRef<str>,
{
    capabilities
        .iter()
        .find_map(|capability| daemon_instance_from_capability(capability.as_ref()))
}

